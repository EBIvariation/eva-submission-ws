CREATE SCHEMA IF NOT EXISTS eva_submissions;

CREATE TABLE eva_submissions.submission_account (
    id VARCHAR(255) PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL,
    login_type VARCHAR(255) NOT NULL,
    primary_email VARCHAR(255) NOT NULL,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    CONSTRAINT uk_submission_account_user_login UNIQUE (user_id, login_type)
);

CREATE TABLE eva_submissions.submission_account_secondary_emails (
    submission_account_id VARCHAR(255) NOT NULL REFERENCES eva_submissions.submission_account(id),
    secondary_emails VARCHAR(255)
);

CREATE TABLE eva_submissions.submission (
    submission_id VARCHAR(255) PRIMARY KEY,
    status VARCHAR(255) NOT NULL,
    submission_account_id VARCHAR(255) NOT NULL REFERENCES eva_submissions.submission_account(id),
    initiation_time TIMESTAMP NOT NULL,
    uploaded_time TIMESTAMP,
    completion_time TIMESTAMP,
    upload_url VARCHAR(255)
);

CREATE TABLE eva_submissions.submission_details (
    submission_id VARCHAR(255) PRIMARY KEY REFERENCES eva_submissions.submission(submission_id),
    project_title VARCHAR(500) NOT NULL,
    project_description VARCHAR(5000) NOT NULL,
    metadata_json JSONB NOT NULL
);

CREATE TABLE eva_submissions.submission_eload (
    submission_id VARCHAR(255) PRIMARY KEY NOT NULL,
    eload INTEGER NOT NULL UNIQUE,
    source VARCHAR(255) NOT NULL
);

CREATE TABLE eva_submissions.submission_processing_status (
    submission_id VARCHAR(255) PRIMARY KEY NOT NULL REFERENCES eva_submissions.submission(submission_id),
    step VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    priority INTEGER NOT NULL DEFAULT 5,
    last_update_time TIMESTAMP NOT NULL
);

CREATE TABLE eva_submissions.submission_processing_status_aud (
    submission_id VARCHAR(255) NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    step VARCHAR(255),
    status VARCHAR(255),
    priority INTEGER,
    last_update_time TIMESTAMP,
    PRIMARY KEY (submission_id, rev)
);

CREATE TABLE eva_submissions.revinfo (
    rev INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp BIGINT
);

ALTER TABLE eva_submissions.submission_processing_status_aud
    ADD CONSTRAINT fk_submission_processing_aud_revinfo FOREIGN KEY (rev) REFERENCES eva_submissions.revinfo(rev);

CREATE TABLE eva_submissions.submission_tracking_details (
    submission_id VARCHAR(255) PRIMARY KEY REFERENCES eva_submissions.submission(submission_id),
    release_date DATE,
    project_accession VARCHAR(255),
    rt_link VARCHAR(255)
);

CREATE TABLE eva_submissions.submission_tracking_details_analysis_accessions (
    submission_id VARCHAR(255) NOT NULL REFERENCES eva_submissions.submission_tracking_details(submission_id),
    analysis_accessions VARCHAR(255)
);

CREATE TABLE eva_submissions.call_home_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_id VARCHAR(255),
    run_id VARCHAR(255),
    event_type VARCHAR(255),
    cli_version VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE,
    runtime_seconds INTEGER,
    executor VARCHAR(255),
    tasks VARCHAR(255),
    raw_payload JSONB NOT NULL
);
